import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync, readdirSync, realpathSync, rmSync, chmodSync} from 'node:fs';
import {spawn, spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {findManagedSource} from './fetch-bundle.mjs';

test('Git 报告同一仓库根的不同路径表示时可复用，子目录仍拒绝', {skip: process.platform === 'win32'}, t => {
  const root = mkdtempSync(path.join(realpathSync(os.tmpdir()), 'yss-source-root-'));
  t.after(() => rmSync(root, {recursive:true, force:true}));
  const repo = path.join(root, 'repo'); mkdirSync(repo);
  const run = (cwd,args) => {const r=spawnSync('git',args,{cwd,encoding:'utf8'});assert.equal(r.status,0,r.stderr);return r.stdout.trim();};
  run(repo,['init','--quiet']);
  run(repo,['config','user.email','test@example.org']);run(repo,['config','user.name','Test']);
  writeFileSync(path.join(repo,'file'),'fixture');run(repo,['add','file']);run(repo,['commit','--quiet','-m','fixture']);
  const commit=run(repo,['rev-parse','HEAD']);mkdirSync(path.join(repo,'nested'));
  const lockBytes=Buffer.from('fixture'), hash=createHash('sha256').update(lockBytes).digest('hex');
  const cache=path.join(root,'cache');mkdirSync(cache);
  const candidate=path.join(cache,`template-source-${hash}-test`);run(root,['clone','--quiet',repo,candidate]);mkdirSync(path.join(candidate,'nested'));
  writeFileSync(candidate+'.ready',hash);
  const realGit=spawnSync('which',['git'],{encoding:'utf8'}).stdout.trim(), bin=path.join(root,'bin');mkdirSync(bin);
  const wrapper=path.join(bin,'git');
  writeFileSync(wrapper,`#!/bin/sh\nif [ "$1" = rev-parse ] && [ "$2" = --show-toplevel ]; then "${realGit}" "$@" | sed 's|$|/.|'; else exec "${realGit}" "$@"; fi\n`);chmodSync(wrapper,0o755);
  const original=process.env.PATH;process.env.PATH=bin+path.delimiter+original;t.after(()=>{process.env.PATH=original;});
  assert.equal(findManagedSource(cache,lockBytes,{profiles:{spec:{templateCommit:commit,sourcePath:'.'}}}),candidate);
  assert.equal(findManagedSource(cache,lockBytes,{profiles:{spec:{templateCommit:commit,sourcePath:'nested'}}}),undefined);
});

test('新来源锁隔离旧默认缓存，显式来源的冲突仍被拒绝', async t => {
  const root = mkdtempSync(path.join(realpathSync(os.tmpdir()), 'yss-source-cache-'));
  t.after(() => rmSync(root, {recursive: true, force: true}));
  const source = path.join(root, 'origin');
  mkdirSync(source);
  const git = (cwd, args) => {
    const result = spawnSync('git', args, {cwd, encoding: 'utf8'});
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  };
  git(source, ['init', '--quiet']);
  git(source, ['config', 'user.email', 'test@example.org']);
  git(source, ['config', 'user.name', 'Test']);
  writeFileSync(path.join(source, 'file'), 'old');
  git(source, ['add', 'file']);
  git(source, ['commit', '--quiet', '-m', 'old']);
  const oldCommit = git(source, ['rev-parse', 'HEAD']);
  git(source, ['tag', 'v5.0.0']);
  const cache = path.join(root, 'cache', 'yss-cli');
  mkdirSync(cache, {recursive: true});
  const stale = path.join(cache, 'template-source');
  git(root, ['clone', '--quiet', '--no-checkout', source, stale]);
  const before = git(stale, ['show-ref']);
  writeFileSync(path.join(source, 'file'), 'new');
  git(source, ['commit', '--quiet', '-am', 'new']);
  const newCommit = git(source, ['rev-parse', 'HEAD']);
  git(source, ['tag', '-f', 'v5.0.0', newCommit]);
  const cli = path.join(root, 'cli');
  mkdirSync(path.join(cli, 'tools/bundle'), {recursive: true});
  mkdirSync(path.join(cli, 'internal/bundle/assets'), {recursive: true});
  mkdirSync(path.join(cli, 'docs'));
  const tools = path.dirname(fileURLToPath(import.meta.url));
  for (const file of ['fetch-bundle.mjs', 'go-environment.mjs', 'baseline-delta.mjs']) copyFileSync(path.join(tools, file), path.join(cli, 'tools', file));
  writeFileSync(path.join(cli, 'go.mod'), 'module fixture\n\ngo 1.22\n');
  writeFileSync(path.join(cli, 'tools/bundle/main.go'), 'package main\nimport("os";"path/filepath")\nfunc main(){a:=os.Args; if e:=os.WriteFile(filepath.Join(a[len(a)-1],"bundles.json.gz"),[]byte("fixture"),0644); e!=nil{panic(e)}}\n');
  writeFileSync(path.join(cli, 'internal/bundle/assets/bundles.json.gz.sha256'), createHash('sha256').update('fixture').digest('hex'));
  writeFileSync(path.join(cli, 'docs/source-lock.json'), JSON.stringify({profiles:{spec:{templateCommit:newCommit, sourcePath:'.', templateTag:'v5.0.0'}}}));
  const module = pathToFileURL(path.join(cli, 'tools/fetch-bundle.mjs')).href;
  const script = `import {fetchBundle} from ${JSON.stringify(module)}; console.log(JSON.stringify(fetchBundle({force:true})))`;
  const env = {...process.env, YSS_SOURCE_SNAPSHOT:path.join(cli,'docs/source-lock.json'), XDG_CACHE_HOME:path.join(root, 'cache'), GIT_CONFIG_COUNT:'1', GIT_CONFIG_KEY_0:`url.${pathToFileURL(source).href}.insteadOf`, GIT_CONFIG_VALUE_0:'https://github.com/iloveZzz/yss-spec-project-template.git'};
  const result = spawnSync(process.execPath, ['--input-type=module', '-e', script], {encoding:'utf8', env});
  assert.equal(result.status, 0, result.stderr);
  assert.equal(JSON.parse(result.stdout).status, 'generated');
  const directories = readdirSync(cache).filter(name => name !== 'template-source' && !name.endsWith('.ready'));
  assert.equal(directories.length, 1);
  assert.equal(git(path.join(cache, directories[0]), ['rev-parse', 'refs/tags/v5.0.0^{commit}']), newCommit);
  assert.equal(git(stale, ['show-ref']), before);
  assert.equal(git(stale, ['rev-parse', 'refs/tags/v5.0.0^{commit}']), oldCommit);
  const explicit = spawnSync(process.execPath, ['--input-type=module', '-e', `import {fetchBundle} from ${JSON.stringify(module)}; fetchBundle({force:true,sourceRoot:${JSON.stringify(stale)}})`], {encoding:'utf8', env});
  assert.notEqual(explicit.status, 0);
  assert.match(explicit.stderr, /模板 tag v5\.0\.0 与固定提交不一致/);
  assert.equal(git(stale, ['show-ref']), before);
  git(source, ['tag', '-f', 'v5.0.0', oldCommit]);
  const lockFile = path.join(cli, 'docs/source-lock.json');
  writeFileSync(lockFile, readFileSync(lockFile, 'utf8') + '\n');
  const previousCache = path.join(cache, `template-source-${createHash('sha256').update(readFileSync(lockFile)).digest('hex')}`);
  git(root, ['clone', '--quiet', '--no-checkout', source, previousCache]);
  const previousRefs = git(previousCache, ['show-ref']);
  const remoteMismatch = spawnSync(process.execPath, ['--input-type=module', '-e', script], {encoding:'utf8', env});
  assert.notEqual(remoteMismatch.status, 0);
  assert.match(remoteMismatch.stderr, /模板 tag v5\.0\.0 与固定提交不一致/);
  assert.match(remoteMismatch.stderr, /缓存准备失败，保留在/);
  assert.equal(git(stale, ['show-ref']), before);
  const failedDirectories = readdirSync(cache).filter(name => name !== 'template-source' && !name.endsWith('.ready'));
  assert.equal(failedDirectories.length, 3);
  git(source, ['tag', '-f', 'v5.0.0', newCommit]);
  const retried = spawnSync(process.execPath, ['--input-type=module', '-e', script], {encoding:'utf8', env});
  assert.equal(retried.status, 0, retried.stderr);
  assert.equal(JSON.parse(retried.stdout).status, 'generated');
  for (const name of failedDirectories) assert.ok(readdirSync(cache).includes(name), '失败目录必须保留');
  assert.equal(git(stale, ['show-ref']), before);
  assert.equal(git(previousCache, ['show-ref']), previousRefs);
  writeFileSync(lockFile, readFileSync(lockFile, 'utf8') + '\n');
  const run = () => new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['--input-type=module', '-e', script], {env});
    let stderr = '';
    child.stderr.on('data', chunk => {stderr += chunk});
    child.on('error', reject);
    child.on('close', status => resolve({status, stderr}));
  });
  for (const result of await Promise.all([run(), run()])) assert.equal(result.status, 0, result.stderr);
  for (const name of failedDirectories) assert.ok(readdirSync(cache).includes(name), '并发执行不能删除已有目录');
  assert.equal(git(stale, ['show-ref']), before);
  assert.equal(git(previousCache, ['show-ref']), previousRefs);
});
