import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {addTrustedArchive,refreshTrustedRegistry,verifyTrustedRegistry} from './trusted-registry.mjs';

const sha = value => createHash('sha256').update(value).digest('hex');
const packed = (version,commit,producer,policy,value) => gzipSync(Buffer.from(JSON.stringify({storageFormatVersion:2,profiles:Object.fromEntries(['spec','backend'].map(profile=>[profile,{profile,templateVersion:version,templateCommit:commit,sourceState:'committed',producer:{commit:producer,sourceState:'committed'},sourcePolicy:{digest:policy}}])),objects:{['a'.repeat(64)]:value}})));
test('受信来源登记、跨版本重算和篡改拒绝',t=>{
 const root=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'yss-trusted-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const dir=path.join(root,'internal/bundle/assets/trusted');fs.mkdirSync(dir,{recursive:true});fs.mkdirSync(path.join(root,'docs/trusted-sources'),{recursive:true});
 fs.writeFileSync(path.join(dir,'registry.json'),'{"schemaVersion":1,"archives":[]}');
 const commit='2'.repeat(40),producer='3'.repeat(40),policy='4'.repeat(64);
 const sourceLock=Buffer.from(JSON.stringify({schemaVersion:5,producer:{commit:producer,sourceState:'committed'},profiles:Object.fromEntries(['spec','backend'].map(profile=>[profile,{profile,templateVersion:'5.0.0',templateCommit:commit,templateTag:'v5.0.0',sourceState:'committed',policyHash:policy}]))}));
 const archive=packed('5.0.0',commit,producer,policy,'YWJj');
 assert.throws(()=>addTrustedArchive(root,archive,archive,'0'.repeat(64),sourceLock,sha(sourceLock)),/摘要/);
 const first=addTrustedArchive(root,archive,archive,sha(archive),sourceLock,sha(sourceLock));
 fs.writeFileSync(path.join(dir,'registry.json'),JSON.stringify(first.registry));
 fs.writeFileSync(path.join(dir,'5.0.0.delta.gz'),first.outputs['5.0.0.delta.gz']);
 fs.writeFileSync(path.join(root,'docs/trusted-sources/5.0.0.json'),sourceLock);
 assert.equal(verifyTrustedRegistry(root,archive).registry.archives.length,1);
 const next=packed('5.1.0','5'.repeat(40),producer,policy,'ZGVm');
 const refreshed=refreshTrustedRegistry(root,archive,next);
 fs.writeFileSync(path.join(dir,'registry.json'),JSON.stringify(refreshed.registry));
 fs.writeFileSync(path.join(dir,'5.0.0.delta.gz'),refreshed.outputs['5.0.0.delta.gz']);
 assert.equal(verifyTrustedRegistry(root,next).registry.archives.length,1);
 const nextLock=Buffer.from(JSON.stringify({schemaVersion:5,producer:{commit:producer,sourceState:'committed'},profiles:Object.fromEntries(['spec','backend'].map(profile=>[profile,{profile,templateVersion:'5.1.0',templateCommit:'5'.repeat(40),templateTag:'v5.1.0',sourceState:'committed',policyHash:policy}]))}));
 const second=addTrustedArchive(root,next,next,sha(next),nextLock,sha(nextLock));
 fs.writeFileSync(path.join(dir,'registry.json'),JSON.stringify(second.registry));
 fs.writeFileSync(path.join(dir,'5.1.0.delta.gz'),second.outputs['5.1.0.delta.gz']);
 fs.writeFileSync(path.join(root,'docs/trusted-sources/5.1.0.json'),nextLock);
 const newest=packed('5.2.0','6'.repeat(40),producer,policy,'Z2hp');
 const all=refreshTrustedRegistry(root,next,newest);
 fs.writeFileSync(path.join(dir,'registry.json'),JSON.stringify(all.registry));
 for(const [name,data] of Object.entries(all.outputs))fs.writeFileSync(path.join(dir,name),data);
 assert.equal(verifyTrustedRegistry(root,newest).registry.archives.length,2);
 fs.writeFileSync(path.join(dir,'5.0.0.delta.gz'),'corrupt');
 assert.throws(()=>verifyTrustedRegistry(root,newest),/摘要/);
});
