func TestSkillsSyncAdoptsNewDefaultsAtomically(t *testing.T) {
	old := standaloneFixture(t)
	item := old.Installations["skills"]
	item.Distribution["installedSkills"] = []string{"extra", "implement"}
	for ref, f := range old.Files {
		if strings.Contains(ref, "/extra/") {
			item.Initial[ref] = f
		}
	}
	old.Installations["skills"] = item
	root, _ := writeInstallationBundleFixture(t, old)
	target := standaloneFixture(t)
	item = target.Installations["skills"]
	item.Distribution["installedSkills"] = []string{"implement", "probe"}
	target.Installations["skills"] = item
	id, err := Detect(root, "spec", false)
	if err != nil {
		t.Fatal(err)
	}
	view, err := target.ForInstallation("skills")
	if err != nil {
		t.Fatal(err)
	}
	d, err := distributionFor(id, view, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"extra", "implement", "probe"}
	if !reflect.DeepEqual(stringsOf(d["installedSkills"]), want) || d["installation"] != "skills" {
		t.Fatalf("distribution: %+v", d)
	}
	p, err := buildCore(root, "spec", "sync", nil, nil, nil, PlanningOptions{target: target})
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range p.Changes {
		if strings.HasPrefix(c.Path, ".template-spec") || c.Path == "yss-project.yaml" {
			t.Fatalf("governance: %s", c.Path)
		}
	}
	if err = applyStandaloneFixture(t, p, target); err != nil {
		t.Fatal(err)
	}
	id, err = Detect(root, "spec", false)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(stringsOf(id.Native.Distribution["installedSkills"]), want) {
		t.Fatal("metadata inconsistent")
	}
	for _, runtime := range []string{"", "claude", "workbuddy"} {
		got, e := ResolveSkills(id, target, want, runtime, "")
		if e != nil || got.Status != "ready" || len(got.Issues) > 0 || len(got.Missing) > 0 {
			t.Fatalf("%s: %+v %v", runtime, got, e)
		}
	}
	repeat, err := buildCore(root, "spec", "sync", nil, nil, nil, PlanningOptions{target: target})
	if err != nil || len(repeat.Changes) != 0 {
		t.Fatalf("repeat: %+v %v", repeat, err)
	}
}

func TestSkillsSyncPreservesUserState(t *testing.T) {
	for _, kind := range []string{"occupied", "symlink", "custom", "permission", "retired", "missing-runtimes", "unknown-runtime", "canonical-only"} {
		t.Run(kind, func(t *testing.T) {
			old := standaloneFixture(t)
			if kind == "canonical-only" {
				item := old.Installations["skills"]
				delete(item.Distribution, "runtimes")
				for ref := range item.Initial {
					if strings.HasPrefix(ref, ".claude/") || strings.HasPrefix(ref, ".workbuddy/") {
						delete(item.Initial, ref)
					}
				}
				old.Installations["skills"] = item
			}
			root, _ := writeInstallationBundleFixture(t, old)
			target := standaloneFixture(t)
			item := target.Installations["skills"]
			item.Distribution["installedSkills"] = []string{"implement", "probe"}
			target.Installations["skills"] = item
			ref := ".agents/skills/implement/references/guide.md"
			switch kind {
			case "occupied":
				ref = ".agents/skills/probe/SKILL.md"
				os.MkdirAll(filepath.Dir(filepath.Join(root, ref)), 0755)
				os.WriteFile(filepath.Join(root, ref), []byte("user content"), 0644)
			case "symlink":
				ref = ".agents/skills/probe"
				os.Symlink(filepath.Join(root, ".agents/skills/implement"), filepath.Join(root, ref))
			case "custom":
				os.WriteFile(filepath.Join(root, ref), []byte("custom user content"), 0644)
			case "permission":
				os.Chmod(filepath.Join(root, ref), 0444)
			case "retired":
				for path := range target.Files {
					if strings.Contains(path, "/implement/") {
						delete(target.Files, path)
					}
				}
			case "missing-runtimes", "unknown-runtime":
				raw, _ := os.ReadFile(filepath.Join(root, MetadataFile))
				var m map[string]any
				json.Unmarshal(raw, &m)
				d := m["distribution"].(map[string]any)
				delete(d, "runtimes")
				if kind == "unknown-runtime" {
					d["runtimes"] = []string{"alien"}
				}
				raw, _ = json.Marshal(m)
				os.WriteFile(filepath.Join(root, MetadataFile), raw, 0644)
			}
			before, err := safefs.Describe(root, ref)
			if err != nil && kind != "symlink" {
				t.Fatal(err)
			}
			meta, _ := os.ReadFile(filepath.Join(root, MetadataFile))
			lock, _ := os.ReadFile(filepath.Join(root, "skills-lock.json"))
			p, e := buildCore(root, "spec", "sync", nil, nil, nil, PlanningOptions{target: target})
			if kind == "canonical-only" {
				if e != nil {
					t.Fatal(e)
				}
				if e = applyStandaloneFixture(t, p, target); e != nil {
					t.Fatal(e)
				}
				return
			}
			if e == nil && p.ReadyToApply {
				t.Fatalf("unsafe sync accepted %s", kind)
			}
			after, _ := safefs.Describe(root, ref)
			now, _ := os.ReadFile(filepath.Join(root, MetadataFile))
			nowLock, _ := os.ReadFile(filepath.Join(root, "skills-lock.json"))
			if before != after || string(meta) != string(now) || string(lock) != string(nowLock) {
				t.Fatal("planning changed user state")
			}
		})
	}
}

func TestSkillsSyncPlanDrift(t *testing.T) {
	b := standaloneFixture(t)
	root, _ := writeInstallationBundleFixture(t, b)
	item := b.Installations["skills"]
	item.Distribution["installedSkills"] = []string{"implement", "probe"}
	b.Installations["skills"] = item
	p, err := buildCore(root, "spec", "sync", nil, nil, nil, PlanningOptions{target: b})
	if err != nil {
		t.Fatal(err)
	}
	meta, _ := os.ReadFile(filepath.Join(root, MetadataFile))
	lock, _ := os.ReadFile(filepath.Join(root, "skills-lock.json"))
	ref := ".agents/skills/implement/references/guide.md"
	os.WriteFile(filepath.Join(root, ref), []byte("new user edit"), 0644)
	ops, err := nativePlanOperations(p)
	if err != nil {
		t.Fatal(err)
	}
	_, err = transaction.ApplyContextWithValidation(context.Background(), root, "sync", ops, p.Inputs, nil, func() error { return verifyAppliedPlan(context.Background(), p, b) })
	if err == nil {
		t.Fatal("input drift accepted")
	}
	if e, ok := err.(*domain.Error); ok && e.Code != "INPUT_DRIFT" && e.Code != "CONFLICT" {
		t.Fatalf("drift: %v", err)
	}
	now, _ := os.ReadFile(filepath.Join(root, MetadataFile))
	nowLock, _ := os.ReadFile(filepath.Join(root, "skills-lock.json"))
	if string(meta) != string(now) || string(lock) != string(nowLock) {
		t.Fatal("partial state update")
	}
}

