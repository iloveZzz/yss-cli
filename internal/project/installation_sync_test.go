func TestSkillsSyncPlansToPreserveRemovedReference(t *testing.T) {
	old := trustedBundle(t, "spec")
	root, _ := writeInstallationBundleFixture(t, old)
	const ref = ".template-spec/agents/backend-architecture-profiles.md"
	refs, err := SelectSkillResources(old, InstallationSkills, []string{"alibaba-java-code-style"}, nil)
	if err != nil {
		t.Fatal(err)
	}
	ensure, err := buildCore(root, "spec", "skills", nil, refs, nil, PlanningOptions{target: old})
	if err != nil || !ensure.ReadyToApply {
		t.Fatalf("ensure: %+v %v", ensure, err)
	}
	writeFixtureChanges(t, root, ensure)
	before, err := os.ReadFile(filepath.Join(root, ref))
	if err != nil {
		t.Fatal(err)
	}
	// The target below models removed reference declarations for planning only.
	target := trustedBundle(t, "spec")
	delete(target.Files, ref)
	item := target.Installations["skills"]
	delete(item.Initial, ref)
	without := func(in []string, value string) []string {
		out := []string{}
		for _, v := range in {
			if v != value {
				out = append(out, v)
			}
		}
		return out
	}
	for owner, paths := range item.SkillReferences {
		item.SkillReferences[owner] = without(paths, ref)
	}
	removedGroups := map[string]bool{}
	for name, paths := range item.ReferenceGroups {
		paths = without(paths, ref)
		if len(paths) == 0 {
			delete(item.ReferenceGroups, name)
			removedGroups[name] = true
		} else {
			item.ReferenceGroups[name] = paths
		}
	}
	for owner, groups := range item.SkillReferenceGroups {
		for name := range removedGroups {
			groups = without(groups, name)
		}
		item.SkillReferenceGroups[owner] = groups
	}
	target.Installations["skills"] = item
	syncTestSnapshot(t, root)
	p, err := buildCore(root, "spec", "sync", nil, nil, nil, PlanningOptions{target: target})
	if err != nil || !p.ReadyToApply {
		t.Fatalf("plan: %+v %v", p, err)
	}
	for _, change := range p.Changes {
		if change.Path == ref {
			t.Fatalf("removed reference changed: %+v", change)
		}
	}
	after, err := os.ReadFile(filepath.Join(root, ref))
	if err != nil || string(after) != string(before) {
		t.Fatalf("reference changed: %v", err)
	}
}

