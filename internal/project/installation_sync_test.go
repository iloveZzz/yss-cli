func writeFixtureChanges(t *testing.T, root string, p *Plan) {
	t.Helper()
	var err error
	for _, c := range p.Changes {
		file := filepath.Join(root, c.Path)
		if c.After.Type == "directory" {
			if err = os.MkdirAll(file, 0755); err != nil {
				t.Fatal(err)
			}
			if err = os.Chmod(file, 0755); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err = os.MkdirAll(filepath.Dir(file), 0755); err != nil {
			t.Fatal(err)
		}
		data, e := base64.StdEncoding.DecodeString(c.Data)
		if e != nil {
			t.Fatal(e)
		}
		if err = os.WriteFile(file, data, os.FileMode(c.After.Mode)); err != nil {
			t.Fatal(err)
		}
		if err = os.Chmod(file, os.FileMode(c.After.Mode)); err != nil {
			t.Fatal(err)
		}
	}
}
